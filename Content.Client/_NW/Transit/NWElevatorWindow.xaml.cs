using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared.ListViewSelector;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NW.Transit;

[GenerateTypedNameReferences]
public sealed partial class NWElevatorWindow : FancyWindow
{
    public event Action<int>? FloorSelected;

    public NWElevatorWindow()
    {
        RobustXamlLoader.Load(this);
        Dismiss.OnPressed += _ => Close();
    }

    public void SetFloors(List<ListViewSelectorEntry> items)
    {
        Floors.Children.Clear();
        SetSize = new Vector2(320, 120 + 30 * Math.Clamp(items.Count, 1, 6));
        if (items.Count == 0)
        {
            Floors.AddChild(new Label { Text = "No available destinations." });
            return;
        }
        for (var i = 0; i < items.Count; i++)
        {
            var index = i;
            var button = new Button { Text = items[i].Name, SetHeight = 28 };
            button.OnPressed += _ => FloorSelected?.Invoke(index);
            Floors.AddChild(button);
        }
    }
}
