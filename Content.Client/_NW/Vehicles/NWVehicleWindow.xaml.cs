using Content.Client.UserInterface.Controls;
using Content.Shared._NW.Vehicles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NW.Vehicles;

[GenerateTypedNameReferences]
public sealed partial class NWVehicleWindow : FancyWindow
{
    public event Action<bool>? OnGearSelected;
    public event Action<bool>? OnLightsSelected;
    private bool _lightsEnabled;
    public event Action<int>? OnSeatSelected;
    public event Action? OnLoadCargo;
    public event Action<NetEntity>? OnUnloadCargo;

    public NWVehicleWindow()
    {
        RobustXamlLoader.Load(this);

        LowGearButton.OnPressed += _ => OnGearSelected?.Invoke(true);
        HighGearButton.OnPressed += _ => OnGearSelected?.Invoke(false);
        LightsButton.OnPressed += _ => OnLightsSelected?.Invoke(!_lightsEnabled);
        LoadCargoButton.OnPressed += _ => OnLoadCargo?.Invoke();
    }

    public void SetState(NWVehicleSeatBoundUserInterfaceState state)
    {
        Title = state.Title;
        LowGearButton.Disabled = state.LowGear;
        HighGearButton.Disabled = !state.LowGear;
        _lightsEnabled = state.LightsEnabled;
        LightsButton.Visible = state.HasOverlights;
        LightsButton.Text = Loc.GetString(state.LightsEnabled ? "nw-vehicle-lights-off" : "nw-vehicle-lights-on");

        var prefix = "ground-vehicle-state";
        var stateName = Loc.GetString($"{prefix}-{state.State.ToString().ToLowerInvariant()}");
        ConsoleHeading.Text = Loc.GetString("ground-vehicle-console");
        CrewHeading.Text = Loc.GetString("ground-vehicle-crew");
        StatusLabel.Text = Loc.GetString("nw-vehicle-window-status", ("state", stateName));

        var occupied = state.Seats.Count(seat => seat.OccupantName != null);
        OccupancyLabel.Text = Loc.GetString("nw-vehicle-window-occupancy",
            ("occupied", occupied),
            ("capacity", state.Seats.Length));

        FuelBar.MaxValue = Math.Max(state.MaxFuel, 1f);
        FuelBar.Value = Math.Clamp(state.Fuel, 0f, FuelBar.MaxValue);
        FuelText.Text = Loc.GetString("nw-vehicle-window-fuel-value",
            ("fuel", MathF.Round(state.Fuel)),
            ("max", MathF.Round(state.MaxFuel)));

        StructureBar.MaxValue = Math.Max(state.MaxStructuralIntegrity, 1f);
        StructureBar.Value = Math.Clamp(state.StructuralIntegrity, 0f, StructureBar.MaxValue);
        StructureText.Text = Loc.GetString("nw-vehicle-window-structure-value",
            ("integrity", MathF.Round(state.StructuralIntegrity)),
            ("max", MathF.Round(state.MaxStructuralIntegrity)));

        FlightCrewList.RemoveAllChildren();
        PassengerList.RemoveAllChildren();

        foreach (var seat in state.Seats)
        {
            var list = seat.Index <= 1 ? FlightCrewList : PassengerList;
            list.AddChild(BuildSeatRow(seat, state.State));
        }

        CargoLabel.Text = Loc.GetString("nw-vehicle-window-cargo-count",
            ("stored", state.Cargo.Length),
            ("capacity", state.CargoCapacity));

        CargoList.RemoveAllChildren();
        if (state.Cargo.Length == 0)
        {
            CargoList.AddChild(new Label
            {
                Text = Loc.GetString("nw-vehicle-cargo-empty"),
                HorizontalExpand = true,
            });
        }
        else
        {
            foreach (var crate in state.Cargo)
            {
                CargoList.AddChild(BuildCargoRow(crate, state.State != NWVehicleState.Parked));
            }
        }

        LoadCargoButton.Disabled = state.Cargo.Length >= state.CargoCapacity ||
            state.State != NWVehicleState.Parked;
    }

    private Control BuildCargoRow(NWVehicleCargoUiState crate, bool disabled)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6),
        };

        row.AddChild(new Label
        {
            Text = crate.Name,
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        });

        var button = new Button
        {
            Text = Loc.GetString("nw-vehicle-cargo-unload"),
            Disabled = disabled,
            MinWidth = 84,
        };

        button.OnPressed += _ => OnUnloadCargo?.Invoke(crate.Crate);

        row.AddChild(button);
        return row;
    }

    private Control BuildSeatRow(NWVehicleSeatUiState seat, NWVehicleState flightState)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6),
        };

        var label = new Label
        {
            Text = seat.Name,
            MinWidth = 132,
            VerticalAlignment = VAlignment.Center,
        };

        var occupant = new Label
        {
            Text = seat.OccupantName ?? Loc.GetString("nw-vehicle-seat-empty"),
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        };

        var button = new Button
        {
            Text = seat.OccupantName == null
                ? Loc.GetString("nw-vehicle-seat-board")
                : Loc.GetString("nw-vehicle-seat-occupied"),
            Disabled = seat.OccupantName != null || flightState != NWVehicleState.Parked,
            MinWidth = 84,
        };

        if (seat.RequiresPilotPerk)
            button.ToolTip = Loc.GetString("nw-vehicle-seat-requires-perk");

        button.OnPressed += _ => OnSeatSelected?.Invoke(seat.Index);

        row.AddChild(label);
        row.AddChild(occupant);
        row.AddChild(button);
        return row;
    }
}
